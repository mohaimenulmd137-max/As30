package com.example.ui.theme

import androidx.compose.material3.MaterialTheme
import androidx.compose.material3.Shapes
import androidx.compose.material3.darkColorScheme
import androidx.compose.runtime.Composable
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.unit.dp
import androidx.compose.foundation.shape.RoundedCornerShape

private val StudioDarkColorScheme = darkColorScheme(
    primary = CyanPlayhead,
    onPrimary = Color(0xFF001F26),
    primaryContainer = CyanMuted,
    onPrimaryContainer = CyanPlayhead,
    secondary = AmberDocumentary,
    onSecondary = Color(0xFF261900),
    secondaryContainer = AmberMuted,
    onSecondaryContainer = AmberDocumentary,
    tertiary = VioletAdjustment,
    onTertiary = Color.White,
    background = StudioObsidian,
    onBackground = TextPrimary,
    surface = StudioSurface,
    onSurface = TextPrimary,
    surfaceVariant = StudioSurfaceElevated,
    onSurfaceVariant = TextSecondary,
    surfaceContainerLowest = StudioObsidian,
    surfaceContainerLow = StudioSurface,
    surfaceContainer = StudioSurfaceElevated,
    surfaceContainerHigh = StudioSurfaceHigh,
    outline = StudioBorder,
    outlineVariant = Color(0xFF1F2536),
    error = CoralAction,
    onError = Color.White
)

val StudioShapes = Shapes(
    extraSmall = RoundedCornerShape(6.dp),
    small = RoundedCornerShape(10.dp),
    medium = RoundedCornerShape(14.dp),
    large = RoundedCornerShape(18.dp),
    extraLarge = RoundedCornerShape(24.dp)
)

@Composable
fun ChitraFlowTheme(
    content: @Composable () -> Unit
) {
    MaterialTheme(
        colorScheme = StudioDarkColorScheme,
        typography = StudioTypography,
        shapes = StudioShapes,
        content = content
    )
}
